-- ISS-019 phase 1: verified email addresses, emailed codes, rate-limit
-- counters, and session tokens hashed at rest. See
-- docs/plans/verified-auth-plan.md.

-- NULL = not verified yet. Accounts that exist before this migration were
-- created before verification existed; production held only the owner's, so
-- they count as verified.
ALTER TABLE users ADD COLUMN email_verified_at TIMESTAMPTZ;
UPDATE users SET email_verified_at = created_at;

-- The cookie keeps the raw token; the table keeps only hex(sha256(token)), so
-- a leaked database or backup can't be replayed as live logins. Hashing the
-- existing rows here keeps everyone logged in across the upgrade.
UPDATE user_sessions SET token = encode(sha256(convert_to(token, 'UTF8')), 'hex');
ALTER TABLE user_sessions RENAME COLUMN token TO token_hash;

-- A 6-digit code sent by email: verify an address, reset a password, or
-- confirm a new address. One live code per user and purpose, so resending
-- replaces the old one.
CREATE TABLE email_codes (
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose    TEXT        NOT NULL CHECK (purpose IN ('verify', 'reset', 'change_email')),
    code_hash  TEXT        NOT NULL,
    -- The address being confirmed; set iff purpose = 'change_email'.
    new_email  TEXT        NOT NULL DEFAULT '',
    attempts   INTEGER     NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, purpose),
    CHECK ((purpose = 'change_email') = (new_email <> ''))
);

-- One row per counted event (a failed login, a mail sent). A limit check is a
-- COUNT over a time window, so limits hold across several web pods.
CREATE TABLE auth_attempts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       TEXT        NOT NULL,
    key        TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX auth_attempts_lookup ON auth_attempts (kind, key, created_at);
